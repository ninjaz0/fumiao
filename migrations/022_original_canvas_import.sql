CREATE TABLE legacy_canvas_records (
 source text NOT NULL,
 collection text NOT NULL,
 legacy_id text NOT NULL,
 workspace_id uuid NOT NULL REFERENCES workspaces,
 payload bytea NOT NULL,
 PRIMARY KEY(source,collection,legacy_id)
);
CREATE INDEX legacy_canvas_records_workspace ON legacy_canvas_records(workspace_id);
-- Preserve completed/failed composition history separately from provider jobs.
-- Import never recreates execution work or capacity reservations.
CREATE TABLE storyboard_exports (
 id uuid PRIMARY KEY,
 public_id text NOT NULL UNIQUE CHECK(public_id ~ '^[a-f0-9]{32}$'),
 ordinal bigint GENERATED BY DEFAULT AS IDENTITY UNIQUE,
 uid uuid NOT NULL,
 owner_id uuid NOT NULL REFERENCES users,
 workspace_id uuid NOT NULL REFERENCES workspaces,
 project_id uuid REFERENCES canvas_documents ON DELETE SET NULL,
 revision integer NOT NULL,
 snapshot bytea NOT NULL,
 state text NOT NULL CHECK(state IN ('queued','running','done','failed','cancelled')),
 result_id uuid REFERENCES assets ON DELETE CASCADE,
 subtitles bytea NOT NULL,
 error bytea NOT NULL,
 created bigint NOT NULL,
 updated bigint NOT NULL,
 UNIQUE(owner_id,uid)
);
CREATE INDEX storyboard_exports_project ON storyboard_exports(project_id,created DESC,ordinal DESC);
CREATE TABLE storyboard_export_refs (
 export_id uuid NOT NULL REFERENCES storyboard_exports ON DELETE CASCADE,
 asset_id uuid NOT NULL REFERENCES assets,
 PRIMARY KEY(export_id,asset_id)
);
