CREATE TABLE job_runs(
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 job uuid REFERENCES jobs ON DELETE SET NULL,
 run_key text NOT NULL UNIQUE, attempt integer NOT NULL CHECK(attempt>=0), node text,
 plugin_id text NOT NULL, plugin_version text NOT NULL, policy jsonb,
 kind text NOT NULL, model text NOT NULL, features jsonb NOT NULL,
 created double precision NOT NULL, queued double precision, started double precision,
 generating double precision, finalizing double precision, uploading double precision, validating double precision,
 finished double precision, status text NOT NULL CHECK(status IN ('running','done','failed','cancelled','interrupted','legacy')),
 phase text NOT NULL, step integer NOT NULL DEFAULT 0, steps integer NOT NULL DEFAULT 20,
 progress jsonb NOT NULL DEFAULT '[]', predicted jsonb NOT NULL DEFAULT '{}', details jsonb NOT NULL DEFAULT '{}',
 valid boolean NOT NULL DEFAULT true,
 FOREIGN KEY(plugin_id,plugin_version) REFERENCES plugin_versions(id,version)
);
CREATE INDEX job_runs_current ON job_runs(job,id DESC);
CREATE INDEX job_runs_samples ON job_runs(id DESC) WHERE status='legacy' OR (status='done' AND valid AND started IS NOT NULL);
CREATE INDEX job_runs_node ON job_runs(node,model,id DESC) WHERE status='done';
