-- Raw original documents are authoritative. Do not convert an earlier prototype
-- projection into source text: it may already have rewritten public media URLs.
CREATE TABLE canvas_documents (
 project_id uuid PRIMARY KEY REFERENCES documents ON DELETE CASCADE,
 title bytea NOT NULL,
 document bytea NOT NULL,
 created bigint NOT NULL,
 updated bigint NOT NULL,
 last_editor uuid NOT NULL REFERENCES users
);
CREATE TABLE canvas_nodes (
 project_id uuid NOT NULL REFERENCES canvas_documents ON DELETE CASCADE,
 node text NOT NULL,
 PRIMARY KEY(project_id,node)
);
CREATE TABLE canvas_media_refs (
 project_id uuid NOT NULL REFERENCES canvas_documents ON DELETE CASCADE,
 node text NOT NULL,
 asset_id uuid NOT NULL REFERENCES assets,
 PRIMARY KEY(project_id,node,asset_id)
);
CREATE INDEX canvas_media_refs_asset ON canvas_media_refs(asset_id);
CREATE TABLE canvas_job_links (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 project_id uuid NOT NULL REFERENCES canvas_documents ON DELETE CASCADE,
 node text NOT NULL,
 job_id uuid REFERENCES jobs ON DELETE SET NULL,
 owner_id uuid NOT NULL REFERENCES users,
 uid uuid NOT NULL,
 inputs bytea NOT NULL,
 created bigint NOT NULL,
 UNIQUE(owner_id,uid)
);
CREATE INDEX canvas_job_links_project ON canvas_job_links(project_id,node,id DESC);
CREATE INDEX canvas_job_links_job ON canvas_job_links(job_id);
CREATE TABLE canvas_run_batches (
 owner_id uuid NOT NULL REFERENCES users,
 uid uuid NOT NULL,
 project_id uuid NOT NULL REFERENCES canvas_documents ON DELETE CASCADE,
 node text NOT NULL,
 count integer NOT NULL,
 result bytea NOT NULL,
 PRIMARY KEY(owner_id,uid)
);
