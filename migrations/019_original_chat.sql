-- The original conversation domain is independent of prototype documents/media jobs.
-- UUID foreign keys are internal; original hex/numeric public IDs stay at the boundary.
-- UTF-8 byte columns retain SQLite text including U+0000 without JSONB sanitization.
CREATE TABLE chat_conversations (
 id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
 public_id text NOT NULL UNIQUE DEFAULT replace(gen_random_uuid()::text,'-','') CHECK(public_id ~ '^[0-9a-f]{32}$'),
 ordinal bigint GENERATED BY DEFAULT AS IDENTITY UNIQUE,
 workspace_id uuid NOT NULL REFERENCES workspaces,
 owner_id uuid NOT NULL REFERENCES users,
 title bytea NOT NULL DEFAULT convert_to('新对话','UTF8'),
 custom_title boolean NOT NULL DEFAULT false,
 model text NOT NULL,
 created double precision NOT NULL,
 updated double precision NOT NULL,
 revision integer NOT NULL DEFAULT 1 CHECK(revision>=1),
 deleted_at double precision
);
CREATE INDEX chat_conversations_space ON chat_conversations(workspace_id,updated DESC,ordinal DESC);
CREATE TABLE chat_messages (
 id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
 public_id bigint GENERATED BY DEFAULT AS IDENTITY (MAXVALUE 9007199254740991) UNIQUE CHECK(public_id BETWEEN 1 AND 9007199254740991),
 conversation_id uuid NOT NULL REFERENCES chat_conversations,
 role text NOT NULL CHECK(role IN ('user','assistant')),
 author_id uuid REFERENCES users,
 content bytea NOT NULL DEFAULT ''::bytea,
 state text NOT NULL CHECK(state IN ('running','complete','failed','stopped','interrupted')),
 model text NOT NULL DEFAULT '',
 created double precision NOT NULL,
 context text NOT NULL DEFAULT '{}',
 reply_to uuid,
 superseded boolean NOT NULL DEFAULT false,
 UNIQUE(id,conversation_id),
 FOREIGN KEY(reply_to,conversation_id) REFERENCES chat_messages(id,conversation_id)
);
CREATE INDEX chat_messages_conversation ON chat_messages(conversation_id,public_id);
CREATE TABLE chat_turns (
 id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
 public_id text NOT NULL UNIQUE DEFAULT replace(gen_random_uuid()::text,'-','') CHECK(public_id ~ '^[0-9a-f]{32}$'),
 uid uuid NOT NULL UNIQUE,
 conversation_id uuid NOT NULL REFERENCES chat_conversations,
 owner_id uuid NOT NULL REFERENCES users,
 user_message uuid NOT NULL,
 assistant_message uuid NOT NULL UNIQUE,
 model text NOT NULL,
 state text NOT NULL CHECK(state IN ('running','complete','failed','stopped','interrupted')),
 created double precision NOT NULL,
 started double precision,
 first_token double precision,
 finished double precision,
 updated double precision NOT NULL,
 usage text NOT NULL DEFAULT '{}',
 error bytea NOT NULL DEFAULT ''::bytea,
 request_id bytea NOT NULL DEFAULT ''::bytea,
 finish_reason bytea NOT NULL DEFAULT ''::bytea,
 plugin_id text,
 plugin_version text,
 config_snapshot text,
 connection_id uuid REFERENCES connections,
 lease_token uuid,
 lease_until double precision,
 FOREIGN KEY(user_message,conversation_id) REFERENCES chat_messages(id,conversation_id),
 FOREIGN KEY(assistant_message,conversation_id) REFERENCES chat_messages(id,conversation_id),
 FOREIGN KEY(plugin_id,plugin_version) REFERENCES plugin_versions,
 CHECK(state!='running' OR (plugin_id IS NOT NULL AND plugin_version IS NOT NULL AND config_snapshot IS NOT NULL)),
 CHECK((lease_token IS NULL)=(lease_until IS NULL))
);
CREATE UNIQUE INDEX chat_one_running ON chat_turns(conversation_id) WHERE state='running';
CREATE INDEX chat_turns_active_owner ON chat_turns(owner_id) WHERE state='running';
CREATE INDEX chat_turns_recovery ON chat_turns(lease_until) WHERE state='running';
CREATE TABLE chat_charges (
 turn_id uuid PRIMARY KEY REFERENCES chat_turns,
 workspace_id uuid NOT NULL REFERENCES wallets,
 owner_id uuid NOT NULL REFERENCES users,
 amount bigint NOT NULL CHECK(amount>0),
 price_key text NOT NULL,
 price_revision integer NOT NULL,
 state text NOT NULL CHECK(state IN ('held','spent','refunded')),
 created bigint NOT NULL
);
CREATE TABLE chat_outbox (
 turn_id uuid PRIMARY KEY REFERENCES chat_turns,
 available_at double precision NOT NULL,
 sent_at double precision
);
CREATE TABLE canvas_chat_links (
 project_id uuid NOT NULL REFERENCES documents ON DELETE CASCADE,
 node text NOT NULL,
 conversation_id uuid NOT NULL REFERENCES chat_conversations,
 created double precision NOT NULL,
 PRIMARY KEY(project_id,node,conversation_id)
);
CREATE TABLE chat_applications (
 uid uuid PRIMARY KEY,
 owner_id uuid NOT NULL REFERENCES users,
 conversation_id uuid NOT NULL REFERENCES chat_conversations,
 message_id uuid NOT NULL REFERENCES chat_messages,
 project_id uuid NOT NULL REFERENCES documents,
 node text NOT NULL,
 mode text NOT NULL CHECK(mode IN ('new','replace')),
 created double precision NOT NULL
);
ALTER TABLE ledger ADD COLUMN chat_turn_id uuid REFERENCES chat_turns;
CREATE INDEX ledger_chat_turn ON ledger(chat_turn_id) WHERE chat_turn_id IS NOT NULL;
